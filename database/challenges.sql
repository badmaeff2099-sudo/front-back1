--
-- Таблица «Челлендж дня»
-- Хранит пул доступных челленджей. Челлендж на текущий день выбирается
-- детерминированно (см. backend/api/challenges/today.php): один календарный
-- день — один челлендж, одинаковый при каждом обновлении страницы.
--
-- Скрипт идемпотентный: title уникален, повторный запуск обновляет описание
-- существующих челленджей и добавляет отсутствующие.
--

CREATE TABLE IF NOT EXISTS public.challenges (
    id          serial PRIMARY KEY,
    title       varchar(255) NOT NULL,
    description text         NOT NULL DEFAULT '',
    active      boolean      NOT NULL DEFAULT true,
    created_at  timestamp without time zone DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS challenges_active_idx
    ON public.challenges (active);

CREATE UNIQUE INDEX IF NOT EXISTS challenges_title_key
    ON public.challenges (title);

